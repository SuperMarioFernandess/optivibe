def test_calibration_spec_scalar_rules() -> None:
    """'measured' requires the scalar; other sources must not carry it."""
    with pytest.raises(ValidationError, match="s_target"):
        CalibrationSpec(source="measured")
    with pytest.raises(ValidationError, match="exclusive"):
        CalibrationSpec(source="model", s_target_a_per_m_s2=-1.0e-7)


def test_nea_from_psd_guards() -> None:
    """The referral rejects non-PSD spectra and degenerate sensitivities."""
    from optivibe.core.types import Spectrum

    freq = np.linspace(0.0, 100.0, 11)
    amp = Spectrum(freq=freq, values=np.ones_like(freq), kind="amplitude")
    with pytest.raises(ValueError, match="PSD"):
        nea_from_psd(amp, 1.0)
    psd = Spectrum(freq=freq, values=np.ones_like(freq), kind="psd")
    with pytest.raises(ValueError, match="positive"):
        nea_from_psd(psd, 0.0)
    with pytest.raises(ValueError, match="grid"):
        nea_from_psd(psd, np.ones(3))


