@pytest.mark.golden
def test_analyze_roundtrip_matches_forward_metrics(tmp_path: Path, forward_b: RunArtifacts) -> None:
    """The analyzer reproduces the source run's own standard-DSP metrics.

    Same samples, same chain (17 §7); the only difference is the dc-level
    estimate (sample mean vs true pedestal), a << 0.1 % effect at this SNR.
    """
    path = tmp_path / "rec.csv"
    _write_record_csv(path, forward_b)
    analysis = analyze_record(_spec(path, "B", {"source": "model"}))
    assert analysis.result is not None
    source = forward_b.result
    # Dominant lines coincide (17 §1 "spectral dominants", same estimator).
    assert analysis.dominant_freqs_hz[0] == pytest.approx(F0, abs=0.5)
    assert analysis.result.dominant_freqs_hz[0] == pytest.approx(
        source.dominant_freqs_hz[0], abs=1e-6
    )
    # Calibrated RMS metrics within the dc-estimate delta (11 §7 DSP recovery).
    for key in ("a", "v", "x"):
        assert analysis.result.rms[key] == pytest.approx(source.rms[key], rel=1e-3)
    # The ISO assessment is the same tract: identical zone and class.
    assert analysis.result.iso is not None and source.iso is not None
    assert analysis.result.iso["zone"] == source.iso["zone"]
    assert analysis.result.iso["machine_class"] == source.iso["machine_class"]
    # THD proxy (2f/1f) is tiny for the linear-regime tone.
    assert analysis.second_harmonic_ratio is not None
    assert analysis.second_harmonic_ratio < 0.01


@pytest.mark.golden
def test_measured_scalar_equal_to_model_is_bit_identical(
    tmp_path: Path, forward_b: RunArtifacts, variant_b: VariantConfig, constants: Constants
) -> None:
    """'measured' with the model scalar reproduces the 'model' source bit-for-bit.

    Pins the injection mechanism (StandardDsp sensitivity_model, SW-52): the
    measured path runs the *same* chain, only the scalar source differs.
    """
    path = tmp_path / "rec.csv"
    _write_record_csv(path, forward_b)
    s_model = target_sensitivity(variant_b, constants)
    a_model = analyze_record(_spec(path, "B", {"source": "model"}))
    a_meas = analyze_record(
        _spec(path, "B", {"source": "measured", "s_target_a_per_m_s2": s_model})
    )
    assert a_model.result is not None and a_meas.result is not None
    np.testing.assert_array_equal(a_meas.result.a, a_model.result.a)
    np.testing.assert_array_equal(a_meas.result.v, a_model.result.v)
    assert a_meas.result.rms == a_model.result.rms


@pytest.mark.golden
def test_bench_source_estimates_the_model_sensitivity(
    tmp_path: Path, forward_b: RunArtifacts, variant_b: VariantConfig, constants: Constants
) -> None:
    """The bench estimate from the paired reference matches |s_target D(f0)|.

    For a single tone the RMS-ratio estimator returns the through sensitivity
    at the tone (doc 05 §2b); at f0 << f1 the plateau scalar within noise.
    """
    path = tmp_path / "rec.csv"
    _write_record_csv(path, forward_b)
    analysis = analyze_record(_spec(path, "B", {"source": "bench"}))
    assert analysis.s_target_bench_estimate is not None
    s_f0 = float(np.abs(dynamic_sensitivity(variant_b, np.asarray([F0]), constants))[0])
    assert abs(analysis.s_target_bench_estimate) == pytest.approx(s_f0, rel=0.02)
    # The sign carries the slope inversion (doc 05 §2): negative for v1.
    assert analysis.s_target_bench_estimate < 0.0
    # And the calibrated recovery lands on the applied excitation.
    assert analysis.result is not None
    applied_rms = float(np.sqrt(np.mean(forward_b.forward.excitation.a_x**2)))
    assert analysis.result.rms["a"] == pytest.approx(applied_rms, rel=0.02)


@pytest.mark.golden
def test_nea_referral_identity(
    tmp_path: Path, forward_b: RunArtifacts, variant_b: VariantConfig, constants: Constants
) -> None:
    """NEA(f) equals sqrt(S_I(f)) / |s_target D(f)| bin-for-bin (doc 05 §7).

    Pins the measured-PSD referral convention: the dynamic roll-up D(f) from
    the (shape-agnostic) cantilever divides the plateau scalar.
    """
    path = tmp_path / "rec.csv"
    _write_record_csv(path, forward_b)
    analysis = analyze_record(_spec(path, "B", {"source": "model"}))
    assert analysis.nea_density is not None and analysis.nea_freq_hz is not None
    s_qs = target_sensitivity(variant_b, constants)
    cantilever = CantileverModel.from_config(constants, variant_b)
    s_f = np.abs(s_qs * cantilever.dynamic_factor(analysis.psd.freq))
    expected = np.sqrt(np.maximum(analysis.psd.values, 0.0)) / s_f
    np.testing.assert_allclose(analysis.nea_density, expected, rtol=1e-12)
    assert analysis.nea_full_band_m_s2 is not None
    assert analysis.nea_full_band_m_s2 > 0.0


