def test_analyze_hdf5_roundtrip(tmp_path: Path, forward_b: RunArtifacts) -> None:
    h5py = pytest.importorskip("h5py")
    det = forward_b.forward.detector
    path = tmp_path / "rec.h5"
    with h5py.File(path, "w") as handle:
        ds = handle.create_dataset("i_pd", data=det.samples)
        ds.attrs["fs"] = det.fs
    spec = AnalyzeSpec.model_validate(
        {
            "kind": "analyze",
            "name": "t",
            "variant": "B",
            "record": {
                "format": "hdf5",
                "path": str(path),
                "dataset": "i_pd",
                "units": "A",
                "fs_attr": "fs",
                "timestamp": TS,
            },
            "calibration": {"source": "model"},
        }
    )
    analysis = analyze_record(spec)
    assert analysis.result is not None
    assert analysis.dominant_freqs_hz[0] == pytest.approx(F0, abs=0.5)


