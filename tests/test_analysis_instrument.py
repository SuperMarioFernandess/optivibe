F0 = 200.0
FS = 5000.0
TS = "2026-07-04T00:00:00"


@pytest.fixture(scope="module")
def constants(config_dir: Path) -> Constants:
    return load_constants(config_dir / "constants.yaml")


@pytest.fixture(scope="module")
def variant_b(config_dir: Path) -> VariantConfig:
    return load_variant("B", config_dir)


@pytest.fixture(scope="module")
def forward_b(variant_b: VariantConfig) -> RunArtifacts:
    """One forward + inverse run of variant B (photodiode + standard DSP)."""
    excitation = SineSpec(
        kind="sine", axis="x", fs_hz=FS, duration_s=1.0, frequency_hz=F0, amplitude_g=1.0
    )
    scenario = ScenarioConfig(
        name="s02-fixture",
        variant="B",
        excitation=excitation,
        stages=StageSelection(detector="photodiode", dsp="standard"),
        seed=7,
    )
    return Pipeline(scenario, variant_b).run()


def _write_record_csv(path: Path, artifacts: RunArtifacts, *, reference: bool = True) -> None:
    """Save the forward photocurrent (and reference accel) as a CSV record (G5)."""
    det = artifacts.forward.detector
    t = np.arange(det.n_samples) / det.fs
    cols = [t, det.samples]
    header = "time_s,i_pd_a"
    if reference:
        cols.append(artifacts.forward.excitation.a_x)
        header += ",a_ref_m_s2"
    np.savetxt(path, np.column_stack(cols), delimiter=",", header=header, comments="", fmt="%.17e")


def _spec(path: Path, variant: str, calibration: dict[str, object] | None) -> AnalyzeSpec:
    record: dict[str, object] = {
        "format": "csv",
        "path": str(path),
        "units": "A",
        "column": "i_pd_a",
        "time_column": "time_s",
        "timestamp": TS,
        "reference": {"channel": "a_ref_m_s2", "units": "m/s^2"},
    }
    return AnalyzeSpec.model_validate(
        {
            "kind": "analyze",
            "name": "t",
            "variant": variant,
            "record": record,
            "calibration": calibration,
        }
    )


