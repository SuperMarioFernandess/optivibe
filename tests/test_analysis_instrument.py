"""Role S-02 analyzer tests: forward -> file -> analyze round-trips (18 G5).

The G5 fixtures are *synthetic*: short records generated by a forward run
(photodiode detector) and saved to the loader formats (doc 20 §5); the golden
references are the metrics of the source run's own standard-DSP result, so the
analyzer is checked against the same tract that produced the record (17 §7).
Tolerances follow doc 11 §7 (DSP recovery; the only analyzer-specific delta is
the dc-level estimate: the record uses the sample mean instead of the true
pedestal). Real E-0/E-3 records will later land additively in ``tests/data/``
per the 18 §5/§6 gates (rule 18 §5(g): golden refer to the base formulas).
"""

