def test_cli_analyze_record_override_and_errors(
    tmp_path: Path, forward_b: RunArtifacts, repo_root: Path
) -> None:
    """--record repoints the descriptor; a missing spec exits with code 2."""
    path = tmp_path / "rec.csv"
    _write_record_csv(path, forward_b)
    spec_path = tmp_path / "spec.yaml"
    spec_path.write_text(
        "\n".join(
            [
                "kind: analyze",
                "name: t",
                "variant: B",
                "record:",
                "  format: csv",
                "  path: does-not-exist.csv",
                "  units: A",
                "  column: i_pd_a",
                "  time_column: time_s",
                f'  timestamp: "{TS}"',
                "calibration:",
                "  source: model",
            ]
        )
    )
    code = cli_main(
        [
            "analyze",
            str(spec_path),
            "--record",
            str(path),
            "--config-dir",
            str(repo_root / "configs"),
        ]
    )
    assert code == 0
    assert cli_main(["analyze", str(tmp_path / "missing.yaml")]) == 2
