def test_model_source_on_sphere_is_loud_g9(tmp_path: Path, forward_b: RunArtifacts) -> None:
    """The model calibration refuses non-cylinder shapes with a G9 pointer."""
    path = tmp_path / "rec.csv"
    _write_record_csv(path, forward_b)
    with pytest.raises(ValueError, match="cylinder-only"):
        analyze_record(_spec(path, "proto_poc", {"source": "model"}))


def test_sphere_with_measured_scalar_works(tmp_path: Path, forward_b: RunArtifacts) -> None:
    """A measured scalar calibrates any shape (proto_poc, sphere) -- G9 kept."""
    path = tmp_path / "rec.csv"
    _write_record_csv(path, forward_b)
    analysis = analyze_record(
        _spec(path, "proto_poc", {"source": "measured", "s_target_a_per_m_s2": -2.0e-7})
    )
    assert analysis.result is not None
    assert analysis.dominant_freqs_hz[0] == pytest.approx(F0, abs=0.5)
    assert analysis.calibration is not None
    assert analysis.calibration["source"] == "measured"


def test_no_calibration_degrades_gracefully(tmp_path: Path, forward_b: RunArtifacts) -> None:
    """Without calibration the scale-free metrics are still produced (20 §5)."""
    path = tmp_path / "rec.csv"
    _write_record_csv(path, forward_b, reference=False)
    spec = _spec(path, "proto_poc", None)
    record = spec.record.model_copy(update={"reference": None})
    analysis = analyze_record(spec.model_copy(update={"record": record}))
    assert analysis.result is None
    assert analysis.nea_density is None
    assert analysis.calibration is None
    assert analysis.dominant_freqs_hz[0] == pytest.approx(F0, abs=0.5)
    assert analysis.second_harmonic_ratio is not None
    assert analysis.i_ac_rms_a > 0.0
    assert analysis.psd.kind == "psd"


